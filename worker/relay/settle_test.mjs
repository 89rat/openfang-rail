import { privateKeyToAccount } from "viem/accounts";
import { decodeFunctionData } from "viem";
import { voucherToCall } from "./settle.mjs";
const USDC="0x036CbD53842c5426634e7929541eC2318f3dCF7e", CHAIN_ID=84532, SELLER="0xc59c85e661d34084a7769f955d17fd38254a6235";
const D={name:"USDC",version:"2",chainId:CHAIN_ID,verifyingContract:USDC};
const T={TransferWithAuthorization:[{name:"from",type:"address"},{name:"to",type:"address"},{name:"value",type:"uint256"},{name:"validAfter",type:"uint256"},{name:"validBefore",type:"uint256"},{name:"nonce",type:"bytes32"}]};
const payer=privateKeyToAccount("0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d");
const m={from:payer.address,to:SELLER,value:5000n,validAfter:0n,validBefore:2000000000n,nonce:"0x"+"9f".repeat(32)};
const signature=await payer.signTypedData({domain:D,types:T,primaryType:"TransferWithAuthorization",message:m});
const voucher={...m,value:m.value.toString(),validAfter:"0",validBefore:"2000000000",signature};
const call=voucherToCall(voucher,USDC);
const dec=decodeFunctionData({abi:[{type:"function",name:"transferWithAuthorization",inputs:[{name:"from",type:"address"},{name:"to",type:"address"},{name:"value",type:"uint256"},{name:"validAfter",type:"uint256"},{name:"validBefore",type:"uint256"},{name:"nonce",type:"bytes32"},{name:"v",type:"uint8"},{name:"r",type:"bytes32"},{name:"s",type:"bytes32"}],outputs:[]}],data:call.data});
let pass=0,fail=0;const chk=(n,c)=>{console.log(`${c?"PASS":"FAIL"}  ${n}`);c?pass++:fail++;};
chk("call targets the USDC contract", call.to===USDC);
chk("decoded from == payer", dec.args[0].toLowerCase()===payer.address.toLowerCase());
chk("decoded to == seller", dec.args[1].toLowerCase()===SELLER.toLowerCase());
chk("decoded value == 5000", dec.args[2]===5000n);
chk("decoded nonce matches", dec.args[5].toLowerCase()===m.nonce);
chk("v is 27 or 28", dec.args[6]===27||dec.args[6]===28);
console.log(`\n${pass} passed, ${fail} failed  (calldata is a valid transferWithAuthorization; broadcast needs your gas key)`);
process.exit(fail?1:0);
